-- Fonte: Wikipedia, "List of FIFA country codes" (seção FIFA member codes), consultada em 2026-10-27.
-- Nomes em português. Países fora da FIFA ficam de fora até haver necessidade.
CREATE TABLE pais_fifa (
    codigo TEXT PRIMARY KEY CHECK (codigo ~ '^[A-Z]{3}$'),
    nome   TEXT NOT NULL UNIQUE CHECK (btrim(nome) <> '')
);

